export type Props = {
  staggerDelay?: number;
  updateDelay?: number;

  screenCount?: number;
};

export type TVScreenProps = {
  index: number;
  screenCount: number;
  previewIndex: number;

  staggerDelay: number;
  updateDelay: number;
};

const staggerDelay = 50;
const updateDelay = 1000;

export function TVScreen(p: TVScreenProps) {
  const [previewIndex, setPreviewIndex] = useState(p.previewIndex);
  const preview = previews[previewIndex];

  useEffect(() => {
    setTimeout(
      () => {
        const newPreviewIndex = randomInt(previews.length);

        if (newPreviewIndex == previewIndex) {
          setPreviewIndex((previewIndex + 1) % previews.length);
          return;
        }

        setPreviewIndex(newPreviewIndex);
      },
      updateDelay + p.screenCount * staggerDelay,
    );
  }, [p.screenCount, previewIndex]);

  return (
    <motion.div
      className={classNames(
        `relative aspect-[4/3] w-full bg-neutral-900 overflow-hidden rounded-lg
        p-1`,
        { 'col-span-2 row-span-2': (p.index) % 10 == 0 },
      )}
    >
      <div className="relative w-full h-full overflow-hidden rounded-lg">
        <div
          className="absolute top-0 left-0 w-full h-full z-10"
          style={{
            background: 'radial-gradient(transparent 70%, rgba(0,0,0,0.4))',
          }}
        />
        <AnimatePresence>
          <motion.div
            key={preview.id}
            initial={{ opacity: 0 }}
            animate={{ opacity: 1 }}
            exit={{ opacity: 0 }}
            transition={{
              delay: p.index * (staggerDelay / 1000),
            }}
          >
            <Image src={preview.src} alt={preview.id} style={{ objectFit: 'cover' }} fill />
          </motion.div>
        </AnimatePresence>
      </div>
    </motion.div>
  );
}

export default function Works(p: Props) {
  const { staggerDelay = 50, updateDelay = 1000, screenCount = 15 } = p;

  const screens = useMemo(() => {
    return new Array(screenCount).fill(0).map((_, index) => {
      return (
        <TVScreen
          // biome-ignore lint/suspicious/noArrayIndexKey: generated by fill.map
          key={index}
          screenCount={screenCount}
          index={index}
          previewIndex={index % previews.length}
          staggerDelay={staggerDelay}
          updateDelay={updateDelay}
        />
      );
    });
  }, [staggerDelay, updateDelay, screenCount]);

  return (
    <div className="absolute top-0 left-0 w-full h-full grid grid-cols-3 md:grid-cols-5 auto-rows-max grid-flow-dense gap-2 blur-sm">
      {screens}
    </div>
  );
}
